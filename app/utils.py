def normalize_reading(reading: str) -> str:
    if not reading:
        return ""
    text = reading.strip()
    table = {}
    for code in range(ord("ァ"), ord("ヶ") + 1):
        table[code] = code - 0x60
    return text.translate(table)


def gojuon_row(reading: str) -> str | None:
    normalized = normalize_reading(reading)
    for ch in normalized:
        if ch in {"ー", "・", " ", "　", "’", "'", "“", "”"}:
            continue
        row = _GOJUON_MAP.get(ch)
        if row:
            return row
    return None


